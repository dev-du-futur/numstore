/* Prices Rollmark's badges and places its tiers. Writes src/odds.h.   make odds
 *
 * Odds of a badge = the chance that a drawn number earns it. Under the draw model every integer of a given length
 * is equally likely (the seed is uniform and grown digits are uniform), so:
 *   P(badge) = sum over lengths L of P(length = L) x (share of L-digit numbers that earn it).
 * Lengths 1 to 7 are counted exactly (every number); 8 to 12 by sampling; longer ones are too rare to matter.
 * The sign, growth and decimal badges use the draw model's own odds.
 * Tiers: where the total EP of 4 million drawn rolls crosses fixed shares (Trashest = worst 2 %, Mythic = best
 * 0.5 %, and so on). */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "roll.h"

#define EP_SCALE 10.0   /* a badge worth 1 roll in N pays 10 x N EP */
#define SAMPLES_LONG 300000
#define TIER_ROLLS 4000000

static uint64_t price[N_BADGES];
static double odds[N_BADGES];

/* P(the integer part ends with exactly `len` digits): seed digit count d, then len - d growth steps among
 * len - 1 later chances (RNGidle's growth model) */
static double length_p(int len) {
  static const double seeds_with[7] = {0, 10, 90, 900, 9000, 90000, 900000};
  double p = 0;
  for (int d = 1; d <= 6 && d <= len; d++) {
    double c = 1;
    for (int i = 1; i <= d - 1; i++) c = c * (len - 1 - (d - 1) + i) / i;   /* C(len-1, d-1) */
    p += seeds_with[d] / 1e6 * c * pow(0.99, d) * pow(0.01, len - d);
  }
  return p;
}

static double at_least(int len) {
  double p = 0;
  for (int l = len; l < len + 40; l++) p += length_p(l);
  return p;
}

static uint64_t s64 = 0x9E3779B97F4A7C15ull;
static uint64_t r64(void) { s64 ^= s64 << 13; s64 ^= s64 >> 7; s64 ^= s64 << 17; return s64; }
static uint32_t r32(void) { return (uint32_t)(r64() >> 32); }

static void count(const char *digits, double w, double *acc) {
  roll_t r;
  roll_from_text(&r.num, digits);
  roll_badges(&r);
  for (int i = 0; i < r.nb; i++) acc[r.badges[i]] += w;
}

static int cmp(const void *a, const void *b) {
  uint64_t x = *(const uint64_t *)a, y = *(const uint64_t *)b;
  return x < y ? 1 : x > y ? -1 : 0;
}

int main(void) {
  static double acc[N_BADGES];
  char buf[24];
  for (int L = 1; L <= 12; L++) {
    double pl = length_p(L);
    if (L <= 7) {
      uint64_t lo = L == 1 ? 0 : (uint64_t)pow(10, L - 1), hi = (uint64_t)pow(10, L);
      double w = pl / (double)(hi - lo);
      for (uint64_t v = lo; v < hi; v++) {
        snprintf(buf, sizeof buf, "%llu", (unsigned long long)v);
        count(buf, w, acc);
      }
    } else {
      double w = pl / SAMPLES_LONG;
      for (int s = 0; s < SAMPLES_LONG; s++) {
        buf[0] = (char)('1' + r64() % 9);
        for (int i = 1; i < L; i++) buf[i] = (char)('0' + r64() % 10);
        buf[L] = 0;
        count(buf, w, acc);
      }
    }
    fprintf(stderr, "length %d done\n", L);
  }
  for (int b = 0; b < N_BADGES; b++) odds[b] = acc[b];
  odds[B_BELOW_ZERO] = 1.0 / 20;
  odds[B_GROW7] = at_least(7);
  odds[B_GROW8] = at_least(8);
  odds[B_GROW9] = at_least(9);
  odds[B_GROW11] = at_least(11);
  for (int k = 1; k <= 4; k++) odds[B_SHARD + k - 1] = 0.01 * pow(0.2, k - 1);
  int bad = 0;
  for (int b = 0; b < N_BADGES; b++) {
    if (odds[b] <= 0) { fprintf(stderr, "badge %s never happens\n", BADGES[b].name); bad = 1; continue; }
    price[b] = (uint64_t)llround(EP_SCALE / odds[b]);
  }
  if (bad) return 1;

  /* tiers, from drawn rolls priced as above */
  static uint64_t ep[TIER_ROLLS];
  roll_t r;
  long none = 0;
  for (int i = 0; i < TIER_ROLLS; i++) {
    roll_draw(&r.num, r32);
    roll_badges(&r);
    roll_ep_with(&r, price);
    ep[i] = r.ep;
    none += r.ep == 0;
  }
  qsort(ep, TIER_ROLLS, sizeof ep[0], cmp);
  static const double share[N_TIERS] = {[T_TRASH] = 0.98, [T_COMMON] = 0.80, [T_UNCOMMON] = 0.45, [T_RARE] = 0.18, [T_EPIC] = 0.06,
                                        [T_ANOMALY] = 0.02, [T_MYTHIC] = 0.005, [T_UNREAL] = 0.0005,
                                        [T_ABERRATION] = 0.00005, [T_OTHERWORLDLY] = 0.000005};
  uint64_t tmin[N_TIERS] = {0};
  for (int t = T_TRASH; t <= T_OTHERWORLDLY; t++) tmin[t] = ep[(int)(share[t] * TIER_ROLLS) - 1];
  tmin[T_CATACLYSMIC] = ep[0];           /* the best of 4 million rolls */
  tmin[T_DIVINE] = ep[0] * 3;
  tmin[T_TRANSCENDENT] = ep[0] * 30;
  for (int t = T_TRASH + 1; t <= T_TRANSCENDENT; t++)
    if (tmin[t] <= tmin[t - 1]) tmin[t] = tmin[t - 1] + 1;

  FILE *f = fopen("src/odds.h", "w");
  if (!f) return 1;
  fprintf(f, "/* Generated by tools/odds.c (make odds), do not edit. */\n#ifndef ODDS_H\n#define ODDS_H\n#include <stdint.h>\n");
  fprintf(f, "/* EP of each badge: %g x (1 / its odds) */\nstatic const uint64_t BADGE_EP[%d] = {\n", EP_SCALE, N_BADGES);
  for (int b = 0; b < N_BADGES; b++) fprintf(f, "  %lluull, /* %s: 1 in %.0f */\n", (unsigned long long)price[b], BADGES[b].name, 1 / odds[b]);
  fprintf(f, "};\n/* where each tier starts, in EP (below Trash: Trashest, the worst 2 %) */\nstatic const uint64_t TIER_MIN[%d] = {", N_TIERS);
  for (int t = 0; t < N_TIERS; t++) fprintf(f, "%llull%s", (unsigned long long)tmin[t], t + 1 < N_TIERS ? ", " : "");
  fprintf(f, "};\n#endif\n");
  fclose(f);

  for (int b = 0; b < N_BADGES; b++) printf("%-20s 1 in %-14.0f %llu EP\n", BADGES[b].name, 1 / odds[b], (unsigned long long)price[b]);
  for (int t = T_TRASH; t <= T_TRANSCENDENT; t++) printf("%-13s from %llu EP\n", TIER_NAMES[t], (unsigned long long)tmin[t]);
  printf("rolls with no badge: %.3f%%\n", 100.0 * none / TIER_ROLLS);
  return 0;
}
