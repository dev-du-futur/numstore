# Builds src/assets.h: anti-aliased fonts (DejaVu Sans Bold, 4 bits per pixel), and src/icon.png.   python tools/make_assets.py [path/to/DejaVuSans-Bold.ttf]
import os, sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
OUT = os.path.join(ROOT, 'src', 'assets.h')
TTF = sys.argv[1] if len(sys.argv) > 1 else r'C:\Windows\Fonts\DejaVuSans-Bold.ttf'
MONO = os.path.join(os.path.dirname(TTF), 'DejaVuSansMono-Bold.ttf')   # numbers, like RNGidle's monospace digits

ASCII = ''.join(chr(c) for c in range(32, 127))
FONTS = [  # name, px, characters
    ('font_s', 11, ASCII),
    ('font_m', 14, ASCII),
    ('font_l', 19, ASCII),
    ('font_num', 34, ' 0123456789-.,H'),
    ('font_title', 30, ' ABCDEFGHIJKLMNOPQRSTUVWXYZ'),
    ('font_gem', 30, ' 0123456789-.,?', MONO),        # the rolled number
    ('font_gem_s', 20, ' 0123456789-.,?', MONO),      # a long rolled number
    ('font_data', 14, ' 0123456789-.,?EPx', MONO),    # EP and counts
    ('font_card', 13, ' 0123456789-.,?', MONO),       # bulk grid cards
    ('font_card_s', 10, ' 0123456789-.,?', MONO),     # long numbers on a card
]

out = []
w = out.append
w('/* Generated by tools/make_assets.py, do not edit. Fonts: DejaVu Sans Bold and DejaVu Sans Mono Bold (Bitstream Vera licence).')
w(' */')
w('#ifndef ASSETS_H\n#define ASSETS_H\n#include <stdint.h>')
w('typedef struct { uint8_t w, h; int8_t xo, yo; uint8_t adv; uint16_t off; } glyph_t;')
w('typedef struct { const glyph_t *g; const uint8_t *bits; uint8_t map[96]; uint8_t ascent, cap; } font_t;')


def pack4(vals):
    b = bytearray()
    for i in range(0, len(vals), 2):
        a = vals[i] >> 4
        c = (vals[i + 1] >> 4) if i + 1 < len(vals) else 0
        b.append(a | (c << 4))
    return b


def carr(name, data, typ='uint8_t', per=40):
    items = [str(x) for x in data]
    lines = [','.join(items[i:i + per]) for i in range(0, len(items), per)]
    w('static const %s %s[%d] = {%s};' % (typ, name, len(data), ',\n'.join(lines)))


for name, px, chars, *ttf in FONTS:
    f = ImageFont.truetype(ttf[0] if ttf else TTF, px)
    ascent, descent = f.getmetrics()
    glyphs, bits = [], bytearray()
    cmap = [255] * 96
    for i, ch in enumerate(chars):
        cmap[ord(ch) - 32] = i
        adv = int(round(f.getlength(ch)))
        bb = f.getbbox(ch, anchor='ls')  # relative to the baseline origin
        if ch == ' ' or bb[2] <= bb[0]:
            glyphs.append((0, 0, 0, 0, adv, len(bits)))
            continue
        x0, y0, x1, y1 = bb
        im = Image.new('L', (x1 - x0, y1 - y0), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor='ls')
        vals = list(im.getdata())
        gw, gh = im.size
        off = len(bits)
        for r in range(gh):
            bits += pack4(vals[r * gw:(r + 1) * gw])
        glyphs.append((gw, gh, x0, y0, adv, off))
    cap = -f.getbbox('H', anchor='ls')[1]
    carr(name + '_bits', bits)
    w('static const glyph_t %s_g[%d] = {%s};' % (name, len(glyphs), ','.join('{%d,%d,%d,%d,%d,%d}' % g for g in glyphs)))
    w('static const font_t %s = {%s_g, %s_bits, {%s}, %d, %d};' % (name, name, name, ','.join(map(str, cmap)), ascent, cap))

# ---------------------------------------------------------------- pictures: item icons and Glim (tools/art.py)
sys.path.insert(0, HERE)
import art
w('typedef struct { uint8_t w, h; const uint16_t *px; const uint8_t *a; } img_t;   /* RGB565, 4-bit alpha */')


def image(name, im):
    px, al = [], []
    for (r, g, b, a) in im.getdata():
        px.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) if a else 0)
        al.append(a)
    carr(name + '_px', px, 'uint16_t', 24)
    carr(name + '_a', pack4(al))
    w('static const img_t %s = {%d, %d, %s_px, %s_a};' % (name, im.width, im.height, name, name))


icons = art.item_icons()
for i, im in enumerate(icons):
    image('icon_%d' % i, im)
w('static const img_t *const ICONS[%d] = {%s};' % (len(icons), ','.join('&icon_%d' % i for i in range(len(icons)))))
for f in range(3):
    image('glim_%d' % f, art.glim(f))
w('static const img_t *const GLIM[3] = {&glim_0, &glim_1, &glim_2};')
w('#endif')

with open(OUT, 'w', newline='\n') as f:
    f.write('\n'.join(out) + '\n')
print('wrote', OUT)

# ---------------------------------------------------------------- icon (55x56): a gold 7 on a glowing card
ico = Image.new('RGB', (55, 56), (0x12, 0x10, 0x24))
d = ImageDraw.Draw(ico)
d.rounded_rectangle((6, 5, 48, 50), 6, fill=(0x2A, 0x1F, 0x4A), outline=(0xFF, 0xB0, 0x20), width=2)
f = ImageFont.truetype(TTF, 34)
d.text((27.5, 28), '7', font=f, fill=(0xFF, 0xC8, 0x40), anchor='mm')
for x, y in ((14, 13), (41, 42), (40, 14)):
    d.ellipse((x - 1.5, y - 1.5, x + 1.5, y + 1.5), fill=(0xFF, 0xF0, 0xA0))
# rounded corners on white, like the calculator's own icons (same as Circle Tap and Infinite Stacker)
mask = Image.new('L', (55 * 8, 56 * 8), 0)
ImageDraw.Draw(mask).rounded_rectangle([0, 0, 55 * 8 - 1, 56 * 8 - 1], radius=56, fill=255)
ico = Image.composite(ico, Image.new('RGB', (55, 56), (255, 255, 255)), mask.resize((55, 56), Image.LANCZOS))
ico.save(os.path.join(ROOT, 'src', 'icon.png'))
