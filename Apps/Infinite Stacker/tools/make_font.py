# Bakes the fonts the game draws over the 3D scene into src/font_data.h.
# DejaVu Sans / DejaVu Sans Bold (Bitstream Vera licence, free to use and embed).
# Each pixel is one byte: high nibble = glyph coverage, low nibble = coverage of the glyph grown by 1 px
# (used for the dark outline of the score).  usage: python tools/make_font.py [fonts dir] > src/font_data.h
import sys
from PIL import Image, ImageDraw, ImageFont

fdir = sys.argv[1] if len(sys.argv) > 1 else "C:/Windows/Fonts"
FONTS = [  # name, file, size, characters
    ("score", "DejaVuSans-Bold.ttf", 26, "0123456789"),
    ("big", "DejaVuSans-Bold.ttf", 19, "".join(chr(c) for c in range(32, 127))),
    ("text", "DejaVuSans.ttf", 13, "".join(chr(c) for c in range(32, 127))),
    ("small", "DejaVuSans.ttf", 11, "".join(chr(c) for c in range(32, 127))),
]

out = ["/* generated by tools/make_font.py from DejaVu Sans (Bitstream Vera licence) */",
       "#include <stdint.h>",
       "typedef struct { uint16_t off; uint8_t w, h; int8_t bx, by; uint8_t adv; } glyph_t;",
       "typedef struct { const glyph_t *g; const uint8_t *px; char first, last; int8_t ascent, line; } font_t;"]
for name, file, size, chars in FONTS:
    f = ImageFont.truetype(f"{fdir}/{file}", size)
    asc, desc = f.getmetrics()
    first, last = ord(chars[0]), ord(chars[-1])
    glyphs, data = [], []
    for c in range(first, last + 1):
        ch = chr(c)
        if ch not in chars:
            glyphs.append((len(data), 0, 0, 0, 0, 0)); continue
        adv = round(f.getlength(ch))
        W, H = size * 3, size * 3
        ox, oy = size, size * 2
        a = Image.new("L", (W, H)); ImageDraw.Draw(a).text((ox, oy), ch, font=f, fill=255, anchor="ls")
        b = Image.new("L", (W, H)); ImageDraw.Draw(b).text((ox, oy), ch, font=f, fill=255, anchor="ls", stroke_width=1, stroke_fill=255)
        box = b.getbbox()
        if not box:
            glyphs.append((len(data), 0, 0, 0, 0, adv)); continue
        x0, y0, x1, y1 = box
        off = len(data)
        for y in range(y0, y1):
            for x in range(x0, x1):
                data.append(((a.getpixel((x, y)) * 15 + 127) // 255) << 4 | ((b.getpixel((x, y)) * 15 + 127) // 255))
        glyphs.append((off, x1 - x0, y1 - y0, x0 - ox, y0 - oy, adv))
    out.append(f"static const uint8_t {name}_px[{max(1, len(data))}] = {{")
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const glyph_t {name}_g[{len(glyphs)}] = {{")
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append(f"static const font_t FONT_{name.upper()} = {{{name}_g, {name}_px, {first}, {last}, {asc}, {asc + desc}}};")
    print(f"{name}: {len(data)} bytes", file=sys.stderr)
print("\n".join(out))
