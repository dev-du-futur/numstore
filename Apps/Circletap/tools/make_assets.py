# Builds src/assets.h: anti-aliased fonts (DejaVu Sans Bold, 4 bits per pixel), the heart icon
# and the built-in maps.   python tools/make_assets.py [path/to/DejaVuSans-Bold.ttf]
import math, os, sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'assets.h')
TTF = sys.argv[1] if len(sys.argv) > 1 else r'C:\Windows\Fonts\DejaVuSans-Bold.ttf'

ASCII = ''.join(chr(c) for c in range(32, 127))
FONTS = [  # name, px, characters
    ('font_s', 11, ASCII),
    ('font_m', 15, ASCII),
    ('font_score', 21, ' Score:0123456789-'),
    ('font_title', 29, ' ABCDEFGHIJKLMNOPQRSTUVWXYZ'),
    ('font_level', 77, '0123456789'),
]

out = []
w = out.append
w('/* Generated by tools/make_assets.py, do not edit. Fonts: DejaVu Sans Bold (Bitstream Vera licence). */')
w('#ifndef ASSETS_H\n#define ASSETS_H\n#include <stdint.h>')
w('typedef struct { uint8_t w, h; int8_t xo, yo; uint8_t adv; uint16_t off; } glyph_t;')
w('typedef struct { const glyph_t *g; const uint8_t *bits; uint8_t map[96]; uint8_t ascent, cap; } font_t;')


def pack4(vals):
    b = bytearray()
    for i in range(0, len(vals), 2):
        a = vals[i] >> 4
        c = (vals[i + 1] >> 4) if i + 1 < len(vals) else 0
        b.append(a | (c << 4))
    return b


def carr(name, data, typ='uint8_t'):
    items = [str(x) for x in data]
    lines = [','.join(items[i:i + 40]) for i in range(0, len(items), 40)]
    w('static const %s %s[%d] = {%s};' % (typ, name, len(data), ',\n'.join(lines)))


total = 0
for name, px, chars in FONTS:
    f = ImageFont.truetype(TTF, px)
    ascent, descent = f.getmetrics()
    glyphs, bits = [], bytearray()
    cmap = [255] * 96
    for i, ch in enumerate(chars):
        cmap[ord(ch) - 32] = i
        adv = int(round(f.getlength(ch)))
        bb = f.getbbox(ch, anchor='ls')  # relative to the baseline origin
        if ch == ' ' or bb[2] <= bb[0]:
            glyphs.append((0, 0, 0, 0, adv, len(bits)))
            continue
        x0, y0, x1, y1 = bb
        im = Image.new('L', (x1 - x0, y1 - y0), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor='ls')
        vals = list(im.getdata())
        gw, gh = im.size
        off = len(bits)
        for r in range(gh):
            bits += pack4(vals[r * gw:(r + 1) * gw])
        glyphs.append((gw, gh, x0, y0, adv, off))
    cap = -f.getbbox('H', anchor='ls')[1] if 'H' in chars else -f.getbbox(chars[1], anchor='ls')[1]
    carr(name + '_bits', bits)
    w('static const glyph_t %s_g[%d] = {%s};' % (name, len(glyphs), ','.join('{%d,%d,%d,%d,%d,%d}' % g for g in glyphs)))
    w('static const font_t %s = {%s_g, %s_bits, {%s}, %d, %d};' % (name, name, name, ','.join(map(str, cmap)), ascent, cap))
    total += len(bits) + len(glyphs) * 8

# ---------------------------------------------------------------- heart (Material "favorite" icon path, 24x24 box)


def cubic(p0, p1, p2, p3, n=12):
    return [tuple((1 - t) ** 3 * a + 3 * (1 - t) ** 2 * t * b + 3 * (1 - t) * t * t * c + t ** 3 * d for a, b, c, d in zip(p0, p1, p2, p3))
            for t in (k / n for k in range(1, n + 1))]


def heart_poly():
    pts = [(12, 21.35)]
    cur = (12, 21.35)
    cur = (cur[0] - 1.45, cur[1] - 1.32); pts.append(cur)
    for seg in [((5.4, 15.36), (2, 12.28), (2, 8.5)), ((2, 5.42), (4.42, 3), (7.5, 3))]:
        pts += cubic(cur, *seg); cur = seg[2]
    rel = [(1.74, 0), (3.41, .81), (4.5, 2.09)]
    seg = tuple((cur[0] + a, cur[1] + b) for a, b in rel); pts += cubic(cur, *seg); cur = seg[2]
    for seg in [((13.09, 3.81), (14.76, 3), (16.5, 3)), ((19.58, 3), (22, 5.42), (22, 8.5))]:
        pts += cubic(cur, *seg); cur = seg[2]
    rel = [(0, 3.78), (-3.4, 6.86), (-8.55, 11.54)]
    seg = tuple((cur[0] + a, cur[1] + b) for a, b in rel); pts += cubic(cur, *seg); cur = seg[2]
    pts.append((12, 21.35))
    return pts


for hn, hs in (('heart14', 14), ('heart10', 10)):
    ss = 8
    im = Image.new('L', (hs * ss, hs * ss), 0)
    k = hs * ss / 24.0
    ImageDraw.Draw(im).polygon([(x * k, y * k) for x, y in heart_poly()], fill=255)
    im = im.resize((hs, hs), Image.BOX)
    carr(hn, list(im.getdata()))

# ---------------------------------------------------------------- built-in maps
# Same format as the original's custom maps: a closed path in -1..1 (y down), drawn at 0.35 x the play area.
# The original only had maps made by players and stored online; these few stand in for them.


def poly(n, r, rot=-math.pi / 2):
    p = [(r * math.cos(rot + 2 * math.pi * i / n), r * math.sin(rot + 2 * math.pi * i / n)) for i in range(n)]
    return p + [p[0]]


def curve(f, n=96):
    p = [f(2 * math.pi * i / n) for i in range(n)]
    return p + [p[0]]


def star():
    p = []
    for i in range(10):
        r = 0.95 if i % 2 == 0 else 0.42
        a = -math.pi / 2 + math.pi * i / 5
        p.append((r * math.cos(a), r * math.sin(a)))
    return p + [p[0]]


def heart_map():
    def f(t):
        x = 16 * math.sin(t) ** 3
        y = 13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t)
        return (x / 17.5, -y / 17.5 - 0.1)
    return curve(f)


MAPS = [
    ('Square', 3, [(-0.8, -0.8), (0.8, -0.8), (0.8, 0.8), (-0.8, 0.8), (-0.8, -0.8)]),
    ('Triangle', 3, poly(3, 0.95, -math.pi / 2)),
    ('Heart', 3, heart_map()),
    ('Infinity', 3, curve(lambda t: (0.95 * math.cos(t) / (1 + math.sin(t) ** 2), 1.3 * math.sin(t) * math.cos(t) / (1 + math.sin(t) ** 2)))),
    ('Star', 5, star()),
    ('Flower', 5, curve(lambda t: ((0.62 + 0.3 * math.cos(5 * t)) * math.cos(t), (0.62 + 0.3 * math.cos(5 * t)) * math.sin(t)), 120)),
]
w('typedef struct { const char *name; uint8_t lives; uint8_t n; const float *xy; float length; } map_t;')
for i, (nm, lives, pts) in enumerate(MAPS):
    flat = []
    for x, y in pts:
        flat += [round(x, 4), round(y, 4)]
    w('static const float map%d_xy[%d] = {%s};' % (i, len(flat), ','.join(repr(float(v)) + 'f' for v in flat)))
    MAPS[i] = (nm, lives, pts)
    total += len(flat) * 4
w('#define N_MAPS %d' % len(MAPS))
w('static const map_t MAPS[N_MAPS] = {%s};' % ','.join(
    '{"%s",%d,%d,map%d_xy,%.6ff}' % (nm, lv, len(p), i, sum(math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(p, p[1:])))
    for i, (nm, lv, p) in enumerate(MAPS)))
w('#endif')
open(OUT, 'w', newline='\n').write('\n'.join(out) + '\n')
print('wrote', OUT, 'about', total, 'bytes of data')
