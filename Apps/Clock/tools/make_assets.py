# Builds src/assets.h (anti-aliased fonts, 4 bits per pixel) and src/icon.png.   python tools/make_assets.py [DejaVuSans-Bold.ttf]
import os, sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
OUT = os.path.join(ROOT, 'src', 'assets.h')
TTF = sys.argv[1] if len(sys.argv) > 1 else r'C:\Windows\Fonts\DejaVuSans-Bold.ttf'

ASCII = ''.join(chr(c) for c in range(32, 127))
FONTS = [  # name, px, characters
    ('font_s', 12, ASCII),
    ('font_m', 15, ASCII),
    ('font_l', 20, ASCII),
    ('font_sec', 40, ' 0123456789:/_'),       # seconds, and the fields on the set screen
    ('font_big', 92, ' 0123456789:'),       # hours and minutes
]

out = []
w = out.append
w('/* Generated by tools/make_assets.py, do not edit. Font: DejaVu Sans Bold (Bitstream Vera licence). */')
w('#ifndef ASSETS_H\n#define ASSETS_H\n#include <stdint.h>')
w('typedef struct { uint8_t w, h; int8_t xo, yo; uint8_t adv; uint16_t off; } glyph_t;')
w('typedef struct { const glyph_t *g; const uint8_t *bits; uint8_t map[96]; uint8_t ascent, cap; } font_t;')


def pack4(vals):
    b = bytearray()
    for i in range(0, len(vals), 2):
        a = vals[i] >> 4
        c = (vals[i + 1] >> 4) if i + 1 < len(vals) else 0
        b.append(a | (c << 4))
    return b


def carr(name, data, per=40):
    items = [str(x) for x in data]
    lines = [','.join(items[i:i + per]) for i in range(0, len(items), per)]
    w('static const uint8_t %s[%d] = {%s};' % (name, len(data), ',\n'.join(lines)))


for name, px, chars in FONTS:
    f = ImageFont.truetype(TTF, px)
    ascent, descent = f.getmetrics()
    glyphs, bits = [], bytearray()
    cmap = [255] * 96
    for i, ch in enumerate(chars):
        cmap[ord(ch) - 32] = i
        adv = int(round(f.getlength(ch)))
        bb = f.getbbox(ch, anchor='ls')  # relative to the baseline origin
        if ch == ' ' or bb[2] <= bb[0]:
            glyphs.append((0, 0, 0, 0, adv, len(bits)))
            continue
        x0, y0, x1, y1 = bb
        im = Image.new('L', (x1 - x0, y1 - y0), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor='ls')
        vals = list(im.getdata())
        gw, gh = im.size
        off = len(bits)
        for r in range(gh):
            bits += pack4(vals[r * gw:(r + 1) * gw])
        glyphs.append((gw, gh, x0, y0, adv, off))
    assert len(bits) < 65536, name
    cap = -f.getbbox('0', anchor='ls')[1]
    carr(name + '_bits', bits)
    w('static const glyph_t %s_g[%d] = {%s};' % (name, len(glyphs), ','.join('{%d,%d,%d,%d,%d,%d}' % g for g in glyphs)))
    w('static const font_t %s = {%s_g, %s_bits, {%s}, %d, %d};' % (name, name, name, ','.join(map(str, cmap)), ascent, cap))
w('#endif')

with open(OUT, 'w', newline='\n') as fh:
    fh.write('\n'.join(out) + '\n')
print('wrote', OUT)

# ---------------------------------------------------------------- icon (55x56): a clock face, drawn 8x and scaled down
S = 8
big = Image.new('RGB', (55 * S, 56 * S), (0x10, 0x1A, 0x2C))
d = ImageDraw.Draw(big)
cx, cy, r = 27.5 * S, 28 * S, 21 * S
d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=(0xF4, 0xF1, 0xE8), outline=(0x5C, 0xC8, 0xFF), width=3 * S)
import math
for i in range(12):
    a = i * math.pi / 6
    r0, r1 = r - 6 * S, r - 3 * S
    d.line((cx + r0 * math.sin(a), cy - r0 * math.cos(a), cx + r1 * math.sin(a), cy - r1 * math.cos(a)),
           fill=(0x10, 0x1A, 0x2C), width=int(1.6 * S) if i % 3 else int(2.6 * S))
def hand(deg, length, width, col):
    a = math.radians(deg)
    d.line((cx, cy, cx + length * math.sin(a), cy - length * math.cos(a)), fill=col, width=width)
hand(300, 10 * S, 3 * S, (0x10, 0x1A, 0x2C))   # hour hand at 10
hand(60, 14 * S, 2 * S, (0x10, 0x1A, 0x2C))    # minute hand at 10
d.ellipse((cx - 2 * S, cy - 2 * S, cx + 2 * S, cy + 2 * S), fill=(0xFF, 0x8A, 0x3D))
ico = big.resize((55, 56), Image.LANCZOS)
# rounded corners on white, like the calculator's own icons (same as the other Numstore apps)
mask = Image.new('L', (55 * 8, 56 * 8), 0)
ImageDraw.Draw(mask).rounded_rectangle([0, 0, 55 * 8 - 1, 56 * 8 - 1], radius=56, fill=255)
ico = Image.composite(ico, Image.new('RGB', (55, 56), (255, 255, 255)), mask.resize((55, 56), Image.LANCZOS))
ico.save(os.path.join(ROOT, 'src', 'icon.png'))
print('wrote icon.png')
